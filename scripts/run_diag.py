"""Checkpoint recall diagnostic (offline branch). For each checkpoint of a SWE run's uncapped reference
trajectories and each method, the method's context at that step is rebuilt from the trajectory prefix
and one reader call answers the checkpoint's questions. Memory policies are replayed over every call of
the prefix, so their memory is what an online policy would hold after exactly these steps.

Questions ask only about steps the memory methods have written to memory (their shared window, which the
question generator replays offline; each memory row checks it against the policy's `recent_start`).
Truncation and masking are references: each of their answers records `fact_visible`, whether the fact's
sources are still in their context.

Questions are generated by a program (bench/swe/recall_questions.py) for every checkpoint of the run and
frozen in questions.jsonl, with its sha256, before any render; a resume regenerates them and refuses a
different file. Answers are scored by deterministic matchers; an abstention answer that is not the exact
phrase goes to the LongMemEval abstention judge. Recall accuracy pools the recall templates only: abstention
is reported as a false-alarm (hallucination) rate, and file-read membership as hit rate, false-alarm rate and
balanced accuracy (an empty memory scores 0.5). Resumable by (checkpoint, method). One example first:
    run_diag.py --run-id diag_smoke --source-run dev_gate --methods flow,truncation --limit 1 --allow-dirty
"""
import argparse
import contextvars
import hashlib
import json
import re
import time
import traceback
from concurrent.futures import ThreadPoolExecutor, as_completed

import yaml

from flexamem.adapters.mswea import EARLIER_HEADER, TOOLS, MemoryPolicy
from flexamem.analysis.tables import flow_choice
from flexamem.bench.common import Results, read_rows, write_manifest
from flexamem.bench.longmemeval.judge import judge
from flexamem.bench.swe.checkpoints import BUDGET, THRESHOLDS, call_cuts, find_checkpoints
from flexamem.bench.swe.recall_questions import ABSTAIN, fact_visible, frozen_bytes, make_questions, write_frozen
from flexamem.bench.swe.runner import MEMORY, REFERENCES, is_infra, load_instances, make_policy
from flexamem.llm.client import ROOT, get_llm
from flexamem.llm.ledger import ledger_context, set_ledger
from flexamem.llm.tokens import count_messages
from flexamem.memory.segmenter import parse_steps, step_text

# the Flow arm and Summary+A-MEM split frozen for SWE in configs/exp/endpoints.yaml (flow / 0.5 while not frozen)
_SPLIT = (yaml.safe_load((ROOT / "configs/exp/endpoints.yaml").read_text()).get("summary_split") or {}).get("swe")
METHODS = (flow_choice()["swe"][0], "amem", f"summary_amem_s{_SPLIT or 50}", "memgas", "readagent", "masking",
           "truncation", "passthrough")
REFS_VISIBLE = ("truncation", "masking")  # references whose answers carry fact_visible
PASSTHROUGH_MAX = 128_000  # the passthrough ceiling is read only when the whole prefix fits this
READ_PROMPT = ("Below is the context an AI coding agent sees at one step of its work on a software issue: the task, "
               "possibly a memory of its earlier work, and its most recent steps. The questions call the agent "
               "\"you\". Answer each question from this context only; if the context does not contain the "
               f"information, answer \"{ABSTAIN}\". Keep each answer short.\n\n"
               "<context>\n{context}\n</context>\n\nQuestions:\n{questions}\n\n"
               "Return a JSON object that maps each question id to its answer.")
_NUM = {w: i for i, w in enumerate("zero one two three four five six seven eight nine ten".split())}
_NUM.update(once=1, twice=2)
_INT = re.compile(r"\b(\d+|" + "|".join(_NUM) + r")\b")
_ANS_PATH = re.compile(r"[\w./-]+\.\w+")
_BARE_FILE = re.compile(r"^[\w-]+\.(py|pyi|pyx|c|h|cfg|ini|toml|txt|rst|md|json|ya?ml|js|html|css)$")


def transcript(ctx: list[dict], n_steps: int) -> str:
    """The context flattened to text: task, memory message, and the recent steps in the format memory
    units use, numbered as in the trajectory (every policy keeps a suffix of the steps)."""
    parts = [f"[system]\n{ctx[0]['content']}", f"[task]\n{ctx[1]['content']}"]
    rest = ctx[2:]
    if rest and rest[0].get("role") == "user" and (rest[0].get("content") or "").startswith(EARLIER_HEADER):
        parts.append(f"[memory]\n{rest[0]['content']}")
        rest = rest[1:]
    steps = parse_steps(rest)
    parts += [step_text(s, n_steps - len(steps) + i) for i, s in enumerate(steps, 1)]
    return "\n\n".join(parts)


def _answer_paths(answer: str) -> set[str]:
    out = set()
    for t in _ANS_PATH.findall(answer):
        t = t.removeprefix("/testbed/").removeprefix("./")
        if "/" in t or _BARE_FILE.match(t):
            out.add(t)
    return out


def score(q: dict, answer: str) -> tuple[bool, str, dict]:
    """(correct, scorer, extra): extra carries `said_yes` for membership and `f1` for path sets."""
    a, m = " ".join(answer.lower().split()), q["match"]
    if m == "abstain":
        if ABSTAIN in a:
            return True, "exact", {}
        ok = judge("judge", "abstention", q["question"], q["explanation"], answer, True, qid=q["qid"])["label"]
        return ok, "judge", {}
    if m == "yesno":
        yes, no = bool(re.search(r"\byes\b", a)), bool(re.search(r"\bno\b", a))
        said = "yes" if yes and not no else "no" if no and not yes else None
        return said == q["gold"], "exact", {"said_yes": said == "yes"}
    if m == "path_set":
        got, gold = set() if ABSTAIN in a else _answer_paths(answer), set(q["gold"])
        return got == gold, "exact", {"f1": 2 * len(got & gold) / (len(got) + len(gold))}
    if ABSTAIN in a:
        return False, "exact", {}
    if m == "passfail":
        got = {("pass" if w.startswith(("pass", "succ")) else "fail")
               for w in re.findall(r"\b(pass(?:ed|es|ing)?|succeed(?:ed|s)?|fail(?:ed|s|ing|ures?)?)\b", a)}
        return got == {q["gold"]}, "exact", {}
    if m == "int":
        return {int(_NUM.get(x, x)) for x in _INT.findall(a)} == {int(q["gold"])}, "exact", {}
    if m == "exception":
        hits = sum(bool(re.search(rf"(?<!\w){re.escape(t)}(?!\w)", a)) for t in q["key_tokens"])
        typed = bool(re.search(rf"\b{re.escape(q['exception_type'].lower())}\b", a))
        return typed and hits >= q["key_need"], "exact", {}
    raise ValueError(m)


def summarize(answers: list[dict]) -> dict:
    """Recall accuracy pooled over the recall templates (abstain and membership excluded), the abstention
    false-alarm rate, and membership hit rate, false-alarm rate and balanced accuracy."""
    def rate(xs):
        return sum(xs) / len(xs) if xs else None
    rec = [x for x in answers if x["template"] not in ("abstain", "membership")]
    pos = [x["said_yes"] for x in answers if x["template"] == "membership" and x["gold"] == "yes"]
    neg = [x["said_yes"] for x in answers if x["template"] == "membership" and x["gold"] == "no"]
    per = {}
    for x in rec:
        per.setdefault(x["template"], [0, 0])
        per[x["template"]][0] += x["correct"]
        per[x["template"]][1] += 1
    hit, fa = rate(pos), rate(neg)
    return {"n_recall": len(rec), "n_correct": sum(x["correct"] for x in rec),
            "accuracy": rate([x["correct"] for x in rec]), "per_template": per,
            "path_set_f1": rate([x["f1"] for x in rec if "f1" in x]),
            "n_abstain": sum(x["template"] == "abstain" for x in answers),
            "abstain_false_alarm_rate": rate([not x["correct"] for x in answers if x["template"] == "abstain"]),
            "member_pos": len(pos), "member_neg": len(neg), "member_hit_rate": hit, "member_false_alarm_rate": fa,
            "member_balanced_accuracy": (hit + 1 - fa) / 2 if pos and neg else None}


def freeze_questions(run_dir, qs: list[dict], sha: str):
    """Write the run's questions once; a resume must have generated the same file."""
    path, sha_path = run_dir / "questions.jsonl", run_dir / "questions.sha256"
    if path.exists():
        old = sha_path.read_text().strip()
        if sha != old or hashlib.sha256(path.read_bytes()).hexdigest() != old:
            raise SystemExit(f"{path} differs from the questions generated now; use a new run id")
    else:
        write_frozen(path, qs)
        sha_path.write_text(sha + "\n")


def run_job(cp, method: str, questions: list[dict], task: str, run_id: str, sha: str) -> dict:
    t0 = time.time()
    with ledger_context(stage="diag", run_id=run_id, cid=cp.cid, iid=cp.iid, method=method, budget=cp.budget):
        policy, error = make_policy(method, cp.budget, task), None
        try:
            if isinstance(policy, MemoryPolicy):  # replay: the memory an online policy holds at this step
                for k, c in enumerate(call_cuts(cp.messages), 1):
                    with ledger_context(step=k):
                        policy.build(cp.messages[:c])
            with ledger_context(step=cp.step):
                ctx, info = policy.build(cp.messages)
        except Exception as e:
            if is_infra(e):
                raise
            error, ctx, info = f"{type(e).__name__}: {e}", None, {}
        answers = []
        if ctx is not None:
            ids = {f"q{i}": q for i, q in enumerate(questions, 1)}
            prompt = READ_PROMPT.format(context=transcript(ctx, len(parse_steps(cp.messages[2:]))),
                                        questions="\n".join(f"{k}: {q['question']}" for k, q in ids.items()))
            schema = {"type": "object", "properties": {k: {"type": "string"} for k in ids},
                      "required": list(ids), "additionalProperties": False}
            try:
                out = get_llm().call("reader", prompt, phase="reader", schema=schema, cache=True)
                scored = [(k, q, *score(q, str(out.get(k, "")))) for k, q in ids.items()]
            except Exception as e:  # a rejected reader or judge prompt is recorded once, not resent on every resume
                if is_infra(e):
                    raise
                error, out, scored = f"{type(e).__name__}: {e}", {}, []
            for k, q, ok, how, extra in scored:
                answers.append({"qid": q["qid"], "template": q["template"], "gold": q["gold"],
                                "answer": out.get(k), "correct": ok, "scorer": how, **extra,
                                **({"fact_visible": fact_visible(q, ctx)} if method in REFS_VISIBLE else {})})
    window = {}
    if isinstance(policy, MemoryPolicy) and ctx is not None:
        expected = questions[0]["window"]["recent_start"]
        window = {"recent_start": info.get("recent_start"), "window_match": info.get("recent_start") == expected}
        if not window["window_match"]:
            print(f"WARNING {cp.cid} {method}: recent_start {info.get('recent_start')} != frozen {expected}", flush=True)
    return {**cp.meta(), "method": method, "error": error, "mode": info.get("mode"),
            "context_tokens": count_messages(ctx, TOOLS) if ctx else None,
            "reader_prompt_tokens": count_messages([{"role": "user", "content": prompt}]) if ctx else None,
            "context": {k: v for k, v in info.items() if k not in ("raw_tokens",)}, "memory": policy.stats(),
            **window, "n_questions": len(questions), **summarize(answers), "answers": answers,
            "questions_sha": sha, "wall_s": round(time.time() - t0, 1), "run_id": run_id}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--source-run", required=True, help="SWE run whose passthrough trajectories are the references")
    ap.add_argument("--budget", type=int, default=BUDGET)
    ap.add_argument("--thresholds", default=",".join(f"{t:g}" for t in THRESHOLDS))
    ap.add_argument("--last-min", type=float, default=None,
                    help="add a 'last' checkpoint when a threshold is never reached but the final raw history >= this * B")
    ap.add_argument("--methods", default=",".join(METHODS))
    ap.add_argument("--limit", type=int, default=0, help="first N checkpoints (with questions) only")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--allow-dirty", action="store_true")
    ap.add_argument("--allow-mixed", action="store_true")
    a = ap.parse_args()
    methods = a.methods.split(",")
    # Sculptor's memory is edited by the agent's own tool calls, which replayed passthrough trajectories do not contain
    assert all((m in MEMORY and m != "sculptor") or m in REFERENCES for m in methods), methods
    thresholds = tuple(float(x) for x in a.thresholds.split(","))

    src = ROOT / "artifacts/runs/swe" / a.source_run
    refs = sorted((r for r in read_rows(src / "results.jsonl", ("iid", "method", "budget"))
                   if r["method"] == "passthrough"), key=lambda r: r["iid"])  # finished episodes only
    cps = [cp for r in refs for cp in find_checkpoints(ROOT / r["traj"], a.budget, thresholds, a.last_min)]
    run_dir = ROOT / "artifacts/runs/diag" / a.run_id
    qs = [q for cp in cps for q in make_questions(cp.meta(), cp.messages)]
    sha = hashlib.sha256(frozen_bytes(qs)).hexdigest()
    write_manifest(run_dir, {**vars(a), "questions_sha256": sha}, a.allow_dirty)  # a dirty-tree refusal writes nothing
    freeze_questions(run_dir, qs, sha)
    by_cp = {}
    for q in qs:
        by_cp.setdefault(q["cid"], []).append(q)
    print(f"{len(refs)} references, {len(cps)} checkpoints, {len(by_cp)} with questions, {len(qs)} questions "
          f"(sha256 {sha[:12]})", flush=True)

    results = Results(run_dir / "results.jsonl", ("cid", "method"), a.allow_mixed)
    set_ledger(ROOT / f"artifacts/ledger/diag_{a.run_id}.jsonl")
    todo_cps = [cp for cp in cps if cp.cid in by_cp][:a.limit or None]
    tasks = {i["instance_id"]: i["problem_statement"] for i in load_instances(sorted({cp.iid for cp in todo_cps}))}
    jobs = [(cp, m) for cp in todo_cps for m in methods if not results.has(cid=cp.cid, method=m)
            and (m != "passthrough" or count_messages(cp.messages, TOOLS) <= PASSTHROUGH_MAX)]
    errors = []
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        futs = {ex.submit(contextvars.copy_context().run, run_job, cp, m, by_cp[cp.cid], tasks[cp.iid], a.run_id, sha):
                (cp.cid, m) for cp, m in jobs}
        for i, f in enumerate(as_completed(futs), 1):
            key = futs[f]
            try:
                row = f.result()
                results.add(row)
                print(f"[{i}/{len(jobs)}] {key} recall {row['n_correct']}/{row['n_recall']} member hit/fa "
                      f"{row['member_hit_rate']}/{row['member_false_alarm_rate']} "
                      f"abstain_fa {row['abstain_false_alarm_rate']} mode={row['mode']} "
                      f"context={row['context_tokens']} error={row['error']}", flush=True)
            except Exception as e:
                errors.append(key)
                with (run_dir / "errors.jsonl").open("a") as fh:
                    fh.write(json.dumps({"key": key, "ts": time.time(), "infra": is_infra(e),
                                         "tb": traceback.format_exc()}) + "\n")
                print(f"[{i}/{len(jobs)}] {key} FAILED\n{traceback.format_exc()}", flush=True)
    print(f"done: {len(jobs) - len(errors)} ok, {len(errors)} failures (rerun on resume) {errors}")
    summary = {m: summarize([x for r in results.rows() if r["method"] == m for x in r["answers"]])
               for m in sorted({r["method"] for r in results.rows()})}  # every method, also when rows are added later
    (run_dir / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    for m, v in summary.items():
        print(m, json.dumps({k: round(x, 3) if isinstance(x, float) else x for k, x in v.items()}))


if __name__ == "__main__":
    main()
